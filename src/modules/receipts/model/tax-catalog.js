// Значение, которым оператор помечает таксу, которой нет в каталоге:
// поле кода превращается в свободный ввод.
export const CUSTOM_TAX_VALUE = '__custom__';

export const AVIA_TAX_OPTIONS = RAW_TAXES.map(([value, name, group, keywords]) => ({
  value,
  name,
  group,
  label: `${value} — ${name}`,
  keywords: `${value} ${name} ${keywords || ''}`,
}));

export const AVIA_TAX_BY_CODE = Object.fromEntries(AVIA_TAX_OPTIONS.map((option) => [option.value, option]));

// Список для выпадающего списка: каталог + строка «другой код» + текущий код
// бланка, даже если поставщик прислал таксу, которой нет в справочнике.
export function aviaTaxOptionsFor(code) {
  const known = String(code || '').trim().toUpperCase();
  const custom = { value: CUSTOM_TAX_VALUE, name: 'Другой код — ввести вручную', group: 'Служебные коды', label: 'Другой код — ввести вручную', keywords: 'другой custom вручную ручной' };
  if (!known || AVIA_TAX_BY_CODE[known]) return [...AVIA_TAX_OPTIONS, custom];
  return [
    { value: known, name: 'Такса поставщика вне справочника', group: 'Из бланка поставщика', label: `${known} — из бланка поставщика`, keywords: known },
    ...AVIA_TAX_OPTIONS,
    custom,
  ];
}

export function aviaTaxName(code, fallback = '') {
  const known = String(code || '').trim().toUpperCase();
  return AVIA_TAX_BY_CODE[known]?.name || fallback;
}

